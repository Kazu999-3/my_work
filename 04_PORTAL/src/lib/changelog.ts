// 書式: date(YYYY-MM-DD), title, items(箇条書き)
//
// 【掲載方針】メンバーが実際に使える変更のみを載せる。
//  載せる  : プレイヤーページ / リーダーボード / 相性 / チーム分け / 試合履歴 /
//            Discordのコマンド・募集・通知 など、一般メンバーが触れるもの
//  載せない: 管理者限定ページ（ダッシュボード・名簿管理・辞典/対面メモ管理・ナレッジ管理・
//            コーチページ・5v5シミュレータ）、内部のリファクタ、セキュリティ強化、
//            インフラ・バッチ移行
//  ※2026-09-23: 加えて**実装の詳細や内部の数値を書かないこと**（「〇〇件を再計算」
//    「××を並列化」「通信に0.5秒かかるため」等）。読むのは一般メンバーなので、
//    「何が変わって、自分にどう関係するか」だけを書く。
//  ※2026-07-29: チャンピオン辞典(/champions)・対面メモ・5v5シミュレータ(旧バトルサーチ/
//    /matchups)・ナレッジ(/admin/knowledge)がすべて管理者専用になったため、これらに触れる
//    過去のエントリは削除・改稿済み。
export interface ChangelogEntry {
  date: string;
  title: string;
  tag?: string;
  items: string[];
}

export function formatChangelogForDiscord(entry: ChangelogEntry, baseUrl: string = 'https://ktm-portal.vercel.app'): string {
  const url = `${baseUrl}/guide?tab=updates`;
  const bulletItems = entry.items.map(item => `・${item}`).join('\n');
  return `📢 **【KTM アップデート情報】** (${entry.date})\n` +
    `✨ **${entry.title}**\n\n` +
    `${bulletItems}\n\n` +
    `📖 **詳しい機能説明・使い方はポータルでチェック！**\n` +
    `👉 ${url}`;
}

